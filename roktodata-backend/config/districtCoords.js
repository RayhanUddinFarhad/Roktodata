// Great-circle distance in km.
export function distanceKm([lat1, lng1], [lat2, lng2]) {
  const rad = Math.PI / 180;
  const a =
    Math.sin(((lat2 - lat1) * rad) / 2) ** 2 +
    Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(((lng2 - lng1) * rad) / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(a));
}

// The district whose town is closest to a point, or null if the point is well outside Bangladesh.
export function nearestDistrict(point) {
  let best = null;
  let bestKm = Infinity;
  for (const [name, coords] of Object.entries(DISTRICT_COORDS)) {
    const km = distanceKm(point, coords);
    if (km < bestKm) [best, bestKm] = [name, km];
  }
  return bestKm <= 120 ? best : null;
}
