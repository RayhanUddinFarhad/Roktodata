// "2026-10-21" -> "২১ অক্টোবর ২০২৬"
export function articleDate(ymd: string) {
  const [y, m, d] = ymd.split("-").map(Number);
  return `${toBanglaNumber(d)} ${MONTHS[m - 1]} ${toBanglaNumber(y)}`;
}

// About 180 Bangla words a minute.
export function readingMinutes(a: Article) {
  const text = a.sections
    .flatMap((s) =>
      s.blocks.flatMap((b) =>
        "p" in b ? [b.p] : "list" in b ? b.list : "steps" in b ? b.steps : "note" in b ? [b.note.text] : b.table.rows.flat(),
      ),
    )
    .join(" ");
  return Math.max(2, Math.round(text.split(/\s+/).length / 180));
}

